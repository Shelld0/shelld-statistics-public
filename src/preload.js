const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('shelld', {
  listAccounts: () => ipcRenderer.invoke('accounts:list'),
  activeAccount: () => ipcRenderer.invoke('accounts:active'),
  createAccount: profile => ipcRenderer.invoke('accounts:create',profile),
  updateAccount: profile => ipcRenderer.invoke('accounts:update',profile),
  selectAccount: id => ipcRenderer.invoke('accounts:select',id),
  deleteAccount: (id,label) => ipcRenderer.invoke('accounts:delete',id,label),
  copyText: text => ipcRenderer.invoke('app:copy-text',String(text)),
  forgetMt5Password: () => ipcRenderer.invoke('accounts:forget-secret'),
  listTrades: () => ipcRenderer.invoke('trades:list'),
  addTrade: trade => ipcRenderer.invoke('trades:add', trade),
  deleteTrade: id => ipcRenderer.invoke('trades:delete', id),
  updateTrade: (id, trade) => ipcRenderer.invoke('trades:update', id, trade),
  listScreenshots: tradeId => ipcRenderer.invoke('screenshots:list', tradeId),
  addScreenshot: (tradeId, timeframe) => ipcRenderer.invoke('screenshots:add', tradeId, timeframe),
  moveLegacyScreenshot: (tradeId, from, to) => ipcRenderer.invoke('screenshots:move',tradeId,from,to),
  deleteScreenshot: (tradeId, timeframe) => ipcRenderer.invoke('screenshots:delete', tradeId, timeframe),
  listExtraScreenshots: tradeId => ipcRenderer.invoke('screenshots-extra:list',tradeId),
  pasteExtraScreenshot: (tradeId,timeframe,dataUrl) => ipcRenderer.invoke('screenshots-extra:paste',tradeId,timeframe,dataUrl),
  addExtraScreenshot: (tradeId,timeframe) => ipcRenderer.invoke('screenshots-extra:add',tradeId,timeframe),
  moveExtraScreenshot: (imageId,timeframe) => ipcRenderer.invoke('screenshots-extra:move',imageId,timeframe),
  deleteExtraScreenshot: imageId => ipcRenderer.invoke('screenshots-extra:delete',imageId),
  getImageOrder: (kind,ownerId) => ipcRenderer.invoke('image-orders:get',kind,ownerId),
  saveImageOrder: (kind,ownerId,keys) => ipcRenderer.invoke('image-orders:save',kind,ownerId,keys),
  readClipboardImage: () => ipcRenderer.invoke('result-images:clipboard'),
  listResultImages: (kind,id) => ipcRenderer.invoke('result-images:list',kind,id),
  addResultImage: (kind,id,dataUrl) => ipcRenderer.invoke('result-images:add',kind,id,dataUrl),
  deleteResultImage: (kind,id) => ipcRenderer.invoke('result-images:delete',kind,id),
  listPlans: () => ipcRenderer.invoke('plans:list'),
  addPlan: plan => ipcRenderer.invoke('plans:add', plan),
  listWeeklyPlans: () => ipcRenderer.invoke('weekly:list'),
  addWeeklyPlan: plan => ipcRenderer.invoke('weekly:add',plan),
  updateWeeklyPlan: (id,plan) => ipcRenderer.invoke('weekly:update',id,plan),
  deleteWeeklyPlan: id => ipcRenderer.invoke('weekly:delete',id),
  listWeeklyAssets: id => ipcRenderer.invoke('weekly-assets:list',id),
  addWeeklyAsset: (planId,asset) => ipcRenderer.invoke('weekly-assets:add',planId,asset),
  updateWeeklyAsset: (assetId,notes) => ipcRenderer.invoke('weekly-assets:update',assetId,notes),
  deleteWeeklyAsset: assetId => ipcRenderer.invoke('weekly-assets:delete',assetId),
  listPlanImages: (planId,assetId) => ipcRenderer.invoke('plan-images:list',planId,assetId),
  pastePlanImage: (planId,assetId,dataUrl) => ipcRenderer.invoke('plan-images:paste',planId,assetId,dataUrl),
  addPlanImage: (planId,assetId) => ipcRenderer.invoke('plan-images:add',planId,assetId),
  deletePlanImage: id => ipcRenderer.invoke('plan-images:delete',id),
  listBacktests: () => ipcRenderer.invoke('backtests:list'),
  addBacktest: bt => ipcRenderer.invoke('backtests:add',bt),
  renameBacktest: (id,title) => ipcRenderer.invoke('backtests:rename',id,title),
  deleteBacktest: id => ipcRenderer.invoke('backtests:delete',id),
  listBacktestTrades: id => ipcRenderer.invoke('backtest-trades:list',id),
  addBacktestTrade: id => ipcRenderer.invoke('backtest-trades:add',id),
  updateBacktestField: (id,key,value) => ipcRenderer.invoke('backtest-trades:field',id,key,value),
  deleteBacktestTrade: id => ipcRenderer.invoke('backtest-trades:delete',id),
  listBacktestImages: id => ipcRenderer.invoke('backtest-images:list',id),
  pasteBacktestImage: (id,timeframe,dataUrl) => ipcRenderer.invoke('backtest-images:paste',id,timeframe,dataUrl),
  addBacktestImage: (id,timeframe) => ipcRenderer.invoke('backtest-images:add',id,timeframe),
  moveBacktestImage: (imageId,timeframe) => ipcRenderer.invoke('backtest-images:move',imageId,timeframe),
  deleteBacktestImage: id => ipcRenderer.invoke('backtest-images:delete',id),
  getSetting: key => ipcRenderer.invoke('settings:get', key),
  setSetting: (key, value) => ipcRenderer.invoke('settings:set', key, value),
  flushStudioPreferences: (accountId, snapshot) => ipcRenderer.sendSync('studio:prefs-flush', accountId, snapshot),
  backup: () => ipcRenderer.invoke('backup:export'),
  backupStatus: () => ipcRenderer.invoke('backup:status'),
  saveBackupSettings: (enabled,keep) => ipcRenderer.invoke('backup:settings',enabled,keep),
  makeAutoBackup: () => ipcRenderer.invoke('backup:run-auto'),
  openAutoBackupFolder: () => ipcRenderer.invoke('backup:open-folder'),
  restore: () => ipcRenderer.invoke('backup:import'),
  exportCsv: () => ipcRenderer.invoke('trades:export-csv'),
  listStudioImages: (scope,tradeId,accountId) => ipcRenderer.invoke('studio-images:list',scope,tradeId,accountId),
  pasteStudioImage: (scope,tradeId,dataUrl,accountId) => ipcRenderer.invoke('studio-images:add',scope,tradeId,dataUrl,accountId),
  deleteStudioImage: id => ipcRenderer.invoke('studio-images:delete',id),
  saveResultAlbum: (coverDataUrl,scope,tradeId,accountId) => ipcRenderer.invoke('exports:save-result-album',coverDataUrl,scope,tradeId,accountId),
  saveImageExport: (dataUrl, defaultName) => ipcRenderer.invoke('exports:save-image', dataUrl, defaultName),
  mt5Connect: config => ipcRenderer.invoke('mt5:connect',config),
  mt5Sync: () => ipcRenderer.invoke('mt5:sync'),
  mt5Disconnect: () => ipcRenderer.invoke('mt5:disconnect'),
  mt5Status: () => ipcRenderer.invoke('mt5:status'),
  onMt5Synced: callback => {
    const listener = (_event, data) => callback(data);
    ipcRenderer.on('mt5:synced', listener);
    return () => ipcRenderer.removeListener('mt5:synced',listener);
  }
});